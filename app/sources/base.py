"""Data-source interface for the agent's structured tools.

The agent never sees SQL or an API shape. It calls a tool with typed parameters; the tool calls one method on a
`CatalogueSource`; the source answers with plain dicts. Swapping the MySQL source for an HTTP API later means
writing one new class that implements this protocol. No tool and no prompt changes.
"""
from __future__ import annotations

from typing import Any, Protocol


class SourceUnavailable(Exception):
    """The structured source cannot be reached (down, not configured, timed out). Tools relay this honestly."""


class CatalogueSource(Protocol):
    name: str

    def search_courses(self, query: str, level: str | None, campus: str | None, limit: int) -> list[dict[str, Any]]: ...
    def get_course(self, course_id: int) -> dict[str, Any] | None: ...
    def get_sections(self, course_id: int, kind: str | None) -> list[dict[str, Any]]: ...
    def get_highlights(self, course_id: int) -> list[dict[str, Any]]: ...
    def get_curriculum(self, course_id: int, year: str | None) -> list[dict[str, Any]]: ...
    def get_roadmap(self, course_id: int) -> list[dict[str, Any]]: ...
    def get_admission_process(self, deanery: str | None) -> list[dict[str, Any]]: ...
    def list_campuses(self) -> list[dict[str, Any]]: ...
    def ping(self) -> bool: ...
